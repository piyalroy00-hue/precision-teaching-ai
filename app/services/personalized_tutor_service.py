"""Phase 3 personalized instruction orchestration.

This service receives a learning target chosen upstream by the BKT and
recommendation layers. It produces instructional content only; it does not
calculate, store, or alter learner mastery.
"""
from typing import Protocol

from app.ai.content_validator import validate_python_example
from app.ai.prompt_generator import TutorPrompt, build_tutor_prompt
from app.ai.tutor import TutorContext, TutorOutput
from app.config.settings import AI_TUTOR_PROVIDER, OPENAI_TUTOR_MODEL


class PromptedTutorProvider(Protocol):
    """Future LLM adapters receive the generated prompt and bounded context."""

    def generate(self, prompt: TutorPrompt, context: TutorContext) -> TutorOutput:
        """Return structured instructional content for the selected target."""


class InvalidGeneratedContentError(ValueError):
    """Raised when generated programming content fails a non-executing check."""


class LocalTemplateTutorProvider:
    """Deterministic development provider; never claims to be generated by an LLM."""

    def generate(self, prompt: TutorPrompt, context: TutorContext) -> TutorOutput:
        topic = context.subtopic or context.topic
        prerequisite_note = (
            f"First recall: {', '.join(context.prerequisite_concepts)}. "
            if context.prerequisite_concepts else ""
        )
        return TutorOutput(
            explanation=(
                f"{topic} is the focus of this {context.difficulty.lower()} lesson. "
                f"{prerequisite_note}{context.learning_objective}"
            ),
            example=(
                f"# Synthetic guided example for {topic}\n"
                "def explain_concept():\n"
                f"    return '{topic}: apply the learning objective one step at a time.'\n\n"
                "print(explain_concept())"
            ),
            step_by_step=(
                f"1. Identify the goal for {topic}.\n"
                "2. Apply the prerequisite idea.\n"
                "3. Check the result against the learning objective."
            ),
            hint=f"Focus on the first small step needed to apply {topic}.",
            practice_question=f"In your own words, how would you apply {topic}?",
            correct_answer=f"A correct response should demonstrate: {context.learning_objective}",
            feedback="Compare your reasoning with the learning objective, then try one small variation.",
        )


class PersonalizedTutorService:
    """Build a versioned prompt and request content from an injected provider."""

    def __init__(self, provider: PromptedTutorProvider | None = None):
        self._provider = provider or self._default_provider()

    @staticmethod
    def _default_provider() -> PromptedTutorProvider:
        if AI_TUTOR_PROVIDER == "local":
            return LocalTemplateTutorProvider()
        if AI_TUTOR_PROVIDER == "openai":
            from app.ai.openai_provider import OpenAITutorProvider
            from os import getenv

            api_key = getenv("OPENAI_API_KEY")
            if not api_key:
                raise RuntimeError("OPENAI_API_KEY is required when AI_TUTOR_PROVIDER=openai.")
            return OpenAITutorProvider(api_key=api_key, model=OPENAI_TUTOR_MODEL)
        raise RuntimeError(f"Unsupported AI_TUTOR_PROVIDER: {AI_TUTOR_PROVIDER}")

    def generate(self, context: TutorContext) -> TutorOutput:
        prompt = build_tutor_prompt(context)
        output = self._provider.generate(prompt, context)
        validation = validate_python_example(output.example)
        if not validation.is_valid:
            raise InvalidGeneratedContentError(validation.message)
        return output